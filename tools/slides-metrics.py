# Writes src/slides/metrics.mjs: the advance widths (em/1000) of the Story slides' type, read from the fonts the render
# loads (src/fonts.ts): FiraGO (Latin, digits, Mkhedruli) at 400/500/600/700 and NotoGeo (the condensed Mtavruli,
# NotoSansGeorgian-VF at width 75) at 500/600/700. src/slides/zone.mjs measures every line with them, so the lint, the
# safe-zone test and the render lay a slide out to the same pixel (the render only shrinks a line the browser finds wider).
#   python3 tools/slides-metrics.py
import io, json, os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = lambda n: os.path.join(ROOT, 'public', 'fonts', n)
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0x10D0, 0x10FB)] + list('„“”‚‘’–—…₾·•°№«»')
MTAV = [chr(c) for c in range(0x1C90, 0x1CBB)]

def widths(font, chars):
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    upm = font['head'].unitsPerEm
    out = {}
    for ch in chars:
        g = cmap.get(ord(ch))
        if g is not None:
            out[ch] = round(hmtx[g][0] * 1000 / upm)
    return out

fira = {w: widths(TTFont(F(f)), CHARS) for w, f in [(400, 'FiraGO-Regular.otf'), (500, 'FiraGO-Medium.otf'), (600, 'FiraGO-SemiBold.otf'), (700, 'FiraGO-Bold.otf')]}
noto = {}
for w in (500, 600, 700):
    vf = TTFont(F('NotoSansGeorgian-VF.ttf'))
    inst = instantiateVariableFont(vf, {'wght': w})
    noto[w] = widths(inst, MTAV)
body = '// generated by tools/slides-metrics.py from public/fonts (do not edit): advance widths in 1/1000 em\n'
body += '// FIRA[weight][char] (FiraGO: Latin, digits, Mkhedruli), NOTO[weight][char] (NotoGeo: the condensed Mtavruli)\n'
body += f'export const FIRA = {json.dumps({str(k): v for k, v in fira.items()}, ensure_ascii=False, separators=(",", ":"))};\n'
body += f'export const NOTO = {json.dumps({str(k): v for k, v in noto.items()}, ensure_ascii=False, separators=(",", ":"))};\n'
open(os.path.join(ROOT, 'src', 'slides', 'metrics.mjs'), 'w').write(body)
print('src/slides/metrics.mjs', len(body), 'bytes')
