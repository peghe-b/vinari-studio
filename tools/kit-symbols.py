#!/usr/bin/env python3
"""Writes src/scenes/kit/symbols.ts: the VINARI app's own icon set (Material Symbols Rounded, Apache License 2.0, plus a few
glyphs the app drew itself: obd_port, storefront_line, brake_alert ...), read from the Android app's vector drawables
(android/app/src/main/res/drawable/sym_*.xml in the Vinari repo), so the films and the Story slides draw the very icons the
app shows. Never SF Symbols (Apple's licence). Run it again after the app adds an icon:

    python3 tools/kit-symbols.py "/path/to/Vinari/android/app/src/main/res/drawable"
"""
import glob, json, os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else None
if not src or not os.path.isdir(src):
    sys.exit('usage: python3 tools/kit-symbols.py <android res/drawable dir>')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'scenes', 'kit', 'symbols.ts')
attr = lambda s, k: (re.search(r'android:%s="([^"]+)"' % k, s) or [None, None])[1]
syms = {}
for f in sorted(glob.glob(os.path.join(src, 'sym_*.xml'))):
    name = os.path.basename(f)[4:-4]
    s = open(f, encoding='utf-8').read()
    vw, vh = float(attr(s, 'viewportWidth')), float(attr(s, 'viewportHeight'))
    dy = -960 if 'android:translateY="960"' in s else 0
    parts = []
    for p in re.findall(r'<path\b(.*?)/>', s, re.S):
        d = attr(p, 'pathData')
        if not d:
            continue
        part = {'d': d}
        if attr(p, 'strokeColor'):
            part['w'] = float(attr(p, 'strokeWidth') or 1)
            if attr(p, 'strokeLineCap'):
                part['cap'] = attr(p, 'strokeLineCap')
            if attr(p, 'strokeLineJoin'):
                part['join'] = attr(p, 'strokeLineJoin')
        parts.append(part)
    if parts:
        syms[name] = {'vb': [0, dy, vw, vh], 'p': parts}
body = json.dumps(syms, ensure_ascii=False, separators=(',', ':'))
with open(out, 'w', encoding='utf-8') as fh:
    fh.write('// generated by tools/kit-symbols.py from the VINARI Android app\'s vector drawables (res/drawable/sym_*.xml), do not edit.\n')
    fh.write('// Material Symbols Rounded (c) Google, Apache License 2.0 (https://github.com/google/material-design-icons); the few glyphs\n')
    fh.write('// the app drew itself (obd_port, storefront_line, brake_alert, brake_signal ...) are VINARI\'s own. Draw them with\n')
    fh.write('// <Sym name="..."/> (./icons.tsx). A part with "w" is a stroke of that width, else a fill; "vb" is the viewBox.\n')
    fh.write('export type SymPart = {d: string; w?: number; cap?: string; join?: string};\n')
    fh.write('export type SymDef = {vb: [number, number, number, number]; p: SymPart[]};\n')
    fh.write('export const SYMBOLS: Record<string, SymDef> = %s;\n' % body)
print('%d symbols -> %s (%d KB)' % (len(syms), os.path.relpath(out), os.path.getsize(out) // 1024))
